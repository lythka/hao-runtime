#!/usr/bin/env python3
"""Sources for tests/guest/bridgeunit.sh: a native helper library, the guest
program that calls it, and the interface-unit records that type the helper.

  bridgeunit_gen.py OUTDIR [N]

  OUTDIR/helper.c   bh_n0..bh_n{N-1}: bool f(int v) = v > 0; on x86_64 written in
                    assembly with 0x5a in every byte above al, which the SysV ABI
                    allows and Apple arm64 callers do not expect. bh_dl_narrow:
                    the same, reached only through dlsym. bh_same, bh_apply,
                    bh_tok (a 32-byte struct by value), bh_refused.
  OUTDIR/guest.c    calls every helper and prints what it got.
  OUTDIR/unit.tsv   records for tools/hao_ifunit.py (N narrow TYPED, EXACT with
                    masks, TYPED 'A', REFUSED).
  OUTDIR/wrong.tsv  the same with bh_apply's callback slot left out of its mask
                    (HAO_BRIDGE_CHECK must name it).
"""
import os, sys

out = sys.argv[1]
N = int(sys.argv[2]) if len(sys.argv) > 2 else 5000
os.makedirs(out, exist_ok=True)

h = ['/* generated by tests/guest/bridgeunit_gen.py */', '#include <stdbool.h>', '#include <stdlib.h>', '',
     '#if defined(__x86_64__)']
asm = []
for k in range(N):
    asm.append('.globl _bh_n%d\n_bh_n%d:\n  movabsq $0x5a5a5a5a5a5a5a5a, %%rax\n  testl %%edi, %%edi\n  setg %%al\n  ret' % (k, k))
asm.append('.globl _bh_dl_narrow\n_bh_dl_narrow:\n  movabsq $0x5a5a5a5a5a5a5a5a, %rax\n  testl %edi, %edi\n  setg %al\n  ret')
h.append('__asm__(".text\\n"')
for a in asm:
    h.append('        "%s\\n"' % a.replace('\n', '\\n'))
h.append(');')
h.append('#else')
for k in range(N):
    h.append('bool bh_n%d(int v) { return v > 0; }' % k)
h.append('bool bh_dl_narrow(int v) { return v > 0; }')
h.append('#endif')
h += ['long bh_same(long a, const long *b) { return a == *b; }',
      'int bh_apply(int (*f)(int), int v) { return f(v); }',
      'typedef struct { unsigned v[8]; } bh_tok_t;',
      'int bh_tok(bh_tok_t t) { int s = 0; for (int k = 0; k < 8; k++) s = s * 3 + (int)t.v[k]; return s; }',
      'void bh_refused(void) {}', '']
open(os.path.join(out, 'helper.c'), 'w').write('\n'.join(h))

g = ['/* generated by tests/guest/bridgeunit_gen.py */', '#include <dlfcn.h>', '#include <stdbool.h>', '#include <stdio.h>',
     '#include <string.h>', '#define N %d' % N]
g += ['bool bh_n%d(int);' % k for k in range(N)]
g.append('static bool (*const tab[N])(int) = {')
g += ['    bh_n%d,' % k for k in range(N)]
g.append('};')
g += ['long bh_same(long a, const long *b);', 'int bh_apply(int (*f)(int), int v);',
      'typedef struct { unsigned v[8]; } bh_tok_t;', 'int bh_tok(bh_tok_t t);', 'void bh_refused(void);',
      '__attribute__((noinline)) static int twice(int x) { return 2 * x; }',
      'int main(int argc, char **argv)', '{',
      '    if (argc > 1 && !strcmp(argv[1], "refused")) { bh_refused(); puts("bh_refused returned"); return 0; }',
      '    long sum = 0;', '    int bad = 0;',
      '    for (int k = 0; k < N; k++) {',
      '        int r = tab[k](k % 3 - 1);', '        sum += r;', '        if (r != (k % 3 == 2)) bad++;', '    }',
      '    printf("narrow: %d of %d results not extended, sum %ld\\n", bad, N, sum);',
      '    printf("narrow first/last: %d %d\\n", (int)bh_n0(1), (int)tab[N - 1](1));',
      '    long v = (long)(void *)twice;',
      '    printf("same: %ld\\n", bh_same(v, &v));',
      '    printf("apply: %d\\n", bh_apply(twice, 21));',
      '    bh_tok_t t = {{1, 2, 3, 4, 5, 6, 7, 8}};',
      '    printf("tok: %d\\n", bh_tok(t));',
      '    bool (*dn)(int) = (bool (*)(int))dlsym(RTLD_DEFAULT, "bh_dl_narrow");',
      '    int d1 = dn(1), d0 = dn(-1);',
      '    printf("dlsym narrow: %d %d\\n", d1, d0);',
      '    int (*dp)(const char *, ...) = (int (*)(const char *, ...))dlsym(RTLD_DEFAULT, "printf");',
      '    dp("dlsym printf: %d %s %.2f\\n", 42, "x", 2.5);',
      '    int (*dsn)(char *, unsigned long, const char *, ...) = (int (*)(char *, unsigned long, const char *, ...))dlsym(RTLD_DEFAULT, "snprintf");',
      '    char sb[64];',
      '    dsn(sb, sizeof sb, "%d-%d-%s", 7, 9, "z");',
      '    printf("dlsym snprintf: %s\\n", sb);',
      '    return 0;', '}', '']
open(os.path.join(out, 'guest.c'), 'w').write('\n'.join(g))


def recs(apply_mask):
    r = ['# generated by tests/guest/bridgeunit_gen.py: name class kind argmask resmask enc why']
    r += ['_bh_n%d\tTYPED\tB\t0x0\t-\t-\t-' % k for k in range(N)]
    r.append('_bh_dl_narrow\tTYPED\tB\t0x0\t-\t-\t-')
    r.append('_bh_same\tEXACT\t-\t0x0\t-\t-\t-')                 # long, const long *: no guest code
    r.append('_bh_apply\tEXACT\t-\t%s\t-\t-\t-' % apply_mask)     # int (*)(int) in x0
    r.append('_bh_tok\tTYPED\tA\t0x0\t-\ti{?=[8I]}\t-')          # 32 bytes by value: by reference on arm64
    r.append('_bh_refused\tREFUSED\t-\t-\t-\t-\ttest: refused by its interface unit')
    return '\n'.join(r) + '\n'


open(os.path.join(out, 'unit.tsv'), 'w').write(recs('0x1'))
open(os.path.join(out, 'wrong.tsv'), 'w').write(recs('0x0'))
