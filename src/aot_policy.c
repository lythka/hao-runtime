/* ---------------------------------------------------------------- hash */

/* 64-bit word-wise multiply-xor hash. Integrity only, not authenticity. */
uint64_t hao_aot_hash64(const void *p, size_t n, uint64_t seed)
{
    const uint8_t *b = p;
    uint64_t h = seed ^ (0x9E3779B97F4A7C15ull * ((uint64_t)n + 1));
    while (n >= 8) {
        uint64_t w;
        memcpy(&w, b, 8);
        h = (h ^ w) * 0xff51afd7ed558ccdull;
        h ^= h >> 29;
        b += 8;
        n -= 8;
    }
    uint64_t w = 0;
    memcpy(&w, b, n);
    h = (h ^ w ^ ((uint64_t)n << 56)) * 0xc4ceb9fe1a85ec53ull;
    return h ^ (h >> 32);
}

uint64_t hao_aot_guest_id(const void *mach_header, uint64_t avail, uint64_t slice_size)
{
    const struct mach_header_64 *h = mach_header;
    uint64_t len = avail < sizeof *h ? avail : sizeof *h;
    if (avail >= sizeof *h && h->sizeofcmds <= avail - sizeof *h) len = sizeof *h + h->sizeofcmds;
    return hao_aot_hash64(mach_header, (size_t)len, slice_size);
}

/* ---------------------------------------------------------- validation */

#define REJ(...) do { if (why && n) snprintf(why, n, __VA_ARGS__); return -1; } while (0)

int hao_aot_check(const void *buf, uint64_t size, const hao_aot_expect *x, hao_aot_view *v, char *why, size_t n)
{
    const uint8_t *b = buf;
    hao_aot_hdr h;
    if ((uintptr_t)buf & 7) REJ("unaligned buffer");
    if (size < sizeof h) REJ("truncated (%llu bytes)", (unsigned long long)size);
    memcpy(&h, b, sizeof h);
    if (memcmp(h.magic, HAO_AOT_MAGIC, 8) != 0) REJ("not a hao AOT v%u cache", HAO_AOT_VERSION);
    if (h.version != HAO_AOT_VERSION) REJ("format version %u, expected %u", h.version, HAO_AOT_VERSION);
    if (h.hdr_size != sizeof h) REJ("header size %u, expected %zu", h.hdr_size, sizeof h);
    if (h.file_size != size) REJ("file is %llu bytes, header says %llu", (unsigned long long)size, (unsigned long long)h.file_size);
    if (size > HAO_AOT_MAX_FILE) REJ("file larger than %llu MB", HAO_AOT_MAX_FILE >> 20);
    if (memcmp(h.uuid, x->uuid, 16) != 0) REJ("guest UUID differs");
    if (memcmp(h.gen, x->gen, 16) != 0) REJ("generated by another hao build");
    if (h.vmsize != x->vmsize) REJ("guest vmsize %#llx, cache says %#llx", (unsigned long long)x->vmsize, (unsigned long long)h.vmsize);
    if (h.guest_id != x->guest_id) REJ("guest load commands differ");
    if (h.nblocks > x->vmsize / 4) REJ("%u blocks for %llu guest instructions", h.nblocks, (unsigned long long)(x->vmsize / 4));
    uint64_t ents_sz = (uint64_t)h.nblocks * sizeof(hao_aot_ent), links_sz = (uint64_t)h.nlinks * sizeof(hao_aot_link);
    uint64_t total;
    if (__builtin_add_overflow((uint64_t)sizeof h, ents_sz, &total) || __builtin_add_overflow(total, links_sz, &total) ||
        __builtin_add_overflow(total, h.code_size, &total) || total != size)
        REJ("sizes do not add up (%u blocks, %u links, %llu code bytes, %llu-byte file)", h.nblocks, h.nlinks,
            (unsigned long long)h.code_size, (unsigned long long)size);
    if (h.code_size < 16) REJ("code area of %llu bytes", (unsigned long long)h.code_size);
    if ((uint64_t)h.nlinks > h.code_size / 5) REJ("%u links in %llu code bytes", h.nlinks, (unsigned long long)h.code_size);
    const uint8_t *payload = b + sizeof h;
    if (hao_aot_hash64(payload, (size_t)(size - sizeof h), 0) != h.payload_hash) REJ("payload hash mismatch");
    const hao_aot_ent *ents = (const hao_aot_ent *)(const void *)payload;
    const hao_aot_link *links = (const hao_aot_link *)(const void *)(payload + ents_sz);
    const uint8_t *code = payload + ents_sz + links_sz;
    for (uint32_t k = 0; k < h.nblocks; k++) {
        uint64_t g = ents[k].guest_off, c = ents[k].code_off;
        if (g & 3) REJ("block %u: guest offset %#llx not 4-aligned", k, (unsigned long long)g);
        bool in = false;
        for (int r = 0; r < x->nranges && !in; r++) in = g >= x->range_lo[r] && g + 4 <= x->range_hi[r];
        if (g >= x->vmsize || !in) REJ("block %u: guest offset %#llx outside the image's code", k, (unsigned long long)g);
        if (c & 15) REJ("block %u: code offset %#llx not 16-aligned", k, (unsigned long long)c);
        if (c < 16 || c >= h.code_size) REJ("block %u: code offset %#llx outside the code area", k, (unsigned long long)c);
        if (k && c <= ents[k - 1].code_off) REJ("block %u: code offsets not increasing", k);
    }
    for (uint32_t k = 0; k < h.nlinks; k++) {
        uint64_t s = links[k].site;
        if (s < 16 || s + 4 > h.code_size) REJ("link %u: site %#llx outside the code area", k, (unsigned long long)s);
        if (links[k].target >= h.nblocks) REJ("link %u: target block %u of %u", k, links[k].target, h.nblocks);
        int32_t rel;
        memcpy(&rel, code + s, 4);
        if ((int64_t)s + 4 + rel != (int64_t)ents[links[k].target].code_off) REJ("link %u does not reach its block", k);
    }
    if (v) { v->hdr = (const hao_aot_hdr *)buf; v->ents = ents; v->links = links; v->code = code; }
    return 0;
}

/* ------------------------------------------------- environment trust */

int hao_env_tier_for(const hao_proc_facts *f)
{
    int t = HAO_ENV_OPEN;
    if (f->pid == 1 || (f->euid == 0 && f->ppid == 1) || f->restricted || f->entitled) t = HAO_ENV_GUARDED;
    if (f->setugid || f->uid != f->euid || f->gid != f->egid) t = HAO_ENV_SETUGID;
    if (f->distrust > t) t = f->distrust > HAO_ENV_SETUGID ? HAO_ENV_SETUGID : f->distrust;
    return t;
}

/* Turn a feature off; the process still runs correctly (more slowly). */
static const char *const off_switches[] = {"HAO_NO_AOT", "HAO_INTERP", "HAO_NO_CHAIN", "HAO_JIT_HELPERS_ONLY", "HAO_NO_VARSNIFF",
                                           "HAO_NO_IFUNITS", "HAO_NATIVE_LIBCXX", "HAO_NO_THUNKS",
                                           "HAO_SIGRETURN_KERNEL", "HAO_NO_PROBE", NULL};
/* Print diagnostics only (to the process's own stderr or the console). */
static const char *const diag_switches[] = {"HAO_VERBOSE", "HAO_CRASH_TRACE", "HAO_NX_STATS", "HAO_WATCHDOG", "HAO_BRIDGE_CHECK",
                                            "HAO_BRIDGE_STATS", "HAO_CODE_ALIAS", NULL};

static bool listed(const char *const *l, const char *name)
{
    for (; *l; l++) if (!strcmp(*l, name)) return true;
    return false;
}

/* Everything not listed above (HAO_CACHE, HAO_TRUST_LIST, HAO_AOT_LEARN, HAO_GUEST_ROOT,
 * HAO_IF_DIR, HAO_FLAGS, HAO_NO_MSGSEND, HAO_NO_CLOSURES, HAO_NO_SWIFTREG,
 * HAO_NO_BLOCK_THUNKS, HAO_NO_SWIFT_THUNKS, HAO_NO_JIT_MEMORY, HAO_BRIDGE_ABORT, HAO_SWIFT_POP, HAO_SIGRETURN_USER, ...) chooses code, paths or
 * bridging: OPEN only. HAO_DIAG_DIR is a diagnostic, but it names a directory a guarded (root) process would create a
 * file in: OPEN only too. */
bool hao_env_switch_allowed(const char *name, int tier)
{
    if (tier <= HAO_ENV_OPEN) return true;
    if (listed(off_switches, name)) return true;
    return tier == HAO_ENV_GUARDED && listed(diag_switches, name);
}

bool hao_entitlements_foreign(const char *xml, size_t n)
{
    static const char *const own[] = {"com.apple.security.cs.allow-jit", "com.apple.security.cs.disable-library-validation",
                                      "com.apple.security.get-task-allow", NULL};
    const char *p = xml, *e = xml + n;
    for (;;) {
        const char *k = memmem(p, (size_t)(e - p), "<key>", 5);
        if (!k) return false;
        k += 5;
        const char *ke = memmem(k, (size_t)(e - k), "</key>", 6);
        if (!ke) return true;                     /* malformed: assume the worst */
        bool ok = false;
        for (const char *const *o = own; *o && !ok; o++) ok = strlen(*o) == (size_t)(ke - k) && !memcmp(*o, k, (size_t)(ke - k));
        if (!ok) return true;
        p = ke + 6;
    }
}

/* ---------------------------------------------------- cache locations */

static bool pw_dir_ok(const char *d)
{
    if (!d || d[0] != '/' || !strcmp(d, "/")) return false;
    if (!strncmp(d, "/var/empty", 10) && (d[10] == 0 || d[10] == '/')) return false;
    if (!strncmp(d, "/private/var/empty", 18) && (d[18] == 0 || d[18] == '/')) return false;
    return strlen(d) + sizeof "/Library/Caches/hao" < sizeof ((hao_aot_dir *)0)->path;
}

int hao_aot_dirs_for(int tier, uid_t euid, const char *pw_dir, const char *hao_cache, hao_aot_dir *out,
                     int *write_idx, char *why, size_t n)
{
    int k = 0;
    *write_idx = -1;
    if (why && n) why[0] = 0;
    if (tier == HAO_ENV_OPEN && hao_cache && hao_cache[0]) {
        if (hao_cache[0] != '/') { if (why && n) snprintf(why, n, "HAO_CACHE=%s is not absolute; AOT is off", hao_cache); return 0; }
        if (strlen(hao_cache) >= sizeof out[0].path) { if (why && n) snprintf(why, n, "HAO_CACHE is too long; AOT is off"); return 0; }
        snprintf(out[0].path, sizeof out[0].path, "%s", hao_cache);
        out[0].kind = HAO_AOT_EXPLICIT;
        *write_idx = 0;
        return 1;
    }
    snprintf(out[k].path, sizeof out[k].path, "%s", HAO_AOT_SYS_RO_DIR);
    out[k++].kind = HAO_AOT_SYS_RO;
    snprintf(out[k].path, sizeof out[k].path, "%s", HAO_AOT_SYS_DIR);
    out[k].kind = HAO_AOT_SYS;
    if (euid == 0 && tier != HAO_ENV_SETUGID) *write_idx = k;
    k++;
    if (tier == HAO_ENV_OPEN && euid >= 501 && euid < 0x80000000u && pw_dir_ok(pw_dir)) {
        size_t l = strlen(pw_dir);
        while (l > 1 && pw_dir[l - 1] == '/') l--;
        snprintf(out[k].path, sizeof out[k].path, "%.*s/Library/Caches/hao", (int)l, pw_dir);
        out[k].kind = HAO_AOT_USER;
        *write_idx = k;
        k++;
    }
    return k;
}

#define FAIL(...) do { if (why && n) snprintf(why, n, __VA_ARGS__); return false; } while (0)

bool hao_aot_stat_ok(const struct stat *st, int kind, int role, uid_t euid, char *why, size_t n)
{
    bool sys = kind == HAO_AOT_SYS || kind == HAO_AOT_SYS_RO;
    if (S_ISLNK(st->st_mode)) FAIL("is a symlink");
    if (role == HAO_AOT_FILE ? !S_ISREG(st->st_mode) : !S_ISDIR(st->st_mode))
        FAIL("not a %s", role == HAO_AOT_FILE ? "regular file" : "directory");
    if (!(st->st_uid == 0 || (!sys && st->st_uid == euid))) FAIL("owned by uid %u", (unsigned)st->st_uid);
    if ((st->st_mode & (S_IWGRP | S_IWOTH)) && !(role == HAO_AOT_ANCESTOR && !sys && (st->st_mode & S_ISVTX)))
        FAIL("writable by group or others (mode %o)", (unsigned)(st->st_mode & 07777));
    return true;
}

/* Does any allow entry grant a right that could change what the path holds
 * (write/add, append/add-subdirectory, delete, delete-child, attributes,
 * security, owner)? Read and search grants are harmless. An entry we cannot
 * read counts as granting. */
bool hao_aot_acl_allows(void *acl)
{
    static const acl_perm_t w[] = {ACL_WRITE_DATA, ACL_APPEND_DATA, ACL_DELETE, ACL_DELETE_CHILD, ACL_WRITE_ATTRIBUTES,
                                   ACL_WRITE_EXTATTRIBUTES, ACL_WRITE_SECURITY, ACL_CHANGE_OWNER};
    if (!acl) return false;
    acl_entry_t e;
    for (int id = ACL_FIRST_ENTRY; acl_get_entry((acl_t)acl, id, &e) == 0; id = ACL_NEXT_ENTRY) {
        acl_tag_t tag;
        acl_permset_t ps;
        if (acl_get_tag_type(e, &tag) != 0) return true;
        if (tag == ACL_EXTENDED_DENY) continue;
        if (acl_get_permset(e, &ps) != 0) return true;
        for (size_t k = 0; k < sizeof w / sizeof w[0]; k++)
            if (acl_get_perm_np(ps, w[k]) != 0) return true;
    }
    return false;
}

/* canon must be canonical (realpath): absolute, no "//", no trailing '/'. */
bool hao_aot_dir_ok(const char *canon, int kind, uid_t euid, char *why, size_t n)
{
    char p[1024], w[256];
    size_t len = strlen(canon);
    if (canon[0] != '/' || len >= sizeof p || strstr(canon, "//") || (len > 1 && canon[len - 1] == '/'))
        FAIL("%s: not a canonical absolute path", canon);
    /* "/", then each prefix ending before a '/' or at the end of canon */
    for (size_t i = 0;;) {
        size_t l = i ? i : 1;
        bool last = l >= len;
        memcpy(p, canon, l);
        p[l] = 0;
        struct stat st;
        if (lstat(p, &st) != 0) FAIL("%s: cannot stat", p);
        if (!hao_aot_stat_ok(&st, kind, last ? HAO_AOT_DIR : HAO_AOT_ANCESTOR, euid, w, sizeof w)) FAIL("%s: %s", p, w);
        acl_t a = acl_get_link_np(p, ACL_TYPE_EXTENDED);
        bool bad = hao_aot_acl_allows(a);
        if (a) acl_free(a);
        if (bad) FAIL("%s: its ACL grants write access", p);
        if (last) return true;
        i = l + 1;
        while (i < len && canon[i] != '/') i++;
    }
}

/* The configured (literal) path may pass through symlinks only if root owns
 * them (/tmp, /var, /etc); the canonical path is then checked in full. */
bool hao_aot_literal_ok(const char *path, char *why, size_t n)
{
    char p[1024];
    size_t len = strlen(path);
    if (path[0] != '/' || len >= sizeof p) FAIL("%s: not an absolute path", path);
    for (size_t i = 1; i <= len; i++) {
        if (i < len && path[i] != '/') continue;
        if (path[i - 1] == '/') continue;
        memcpy(p, path, i);
        p[i] = 0;
        struct stat st;
        if (lstat(p, &st) != 0) return true;      /* the rest does not exist yet */
        if (S_ISLNK(st.st_mode) && st.st_uid != 0) FAIL("%s is a symlink owned by uid %u", p, (unsigned)st.st_uid);
    }
    return true;
}
