/*
 * hao — AOT cache validation and trust policy (pure parts; see hao/aot.h).
 * No runtime state: everything here takes its inputs as arguments, so
 * tests/aot/policy.c links it from libhaocore.a.
 */
#include "hao/aot.h"
#include <CommonCrypto/CommonDigest.h>
#include <mach-o/loader.h>
#include <stdio.h>
#include <string.h>
#include <sys/acl.h>

/* ---------------------------------------------------------------- hash */

/* 64-bit word-wise multiply-xor hash. Integrity only, not authenticity. */
uint64_t hao_aot_hash64(const void *p, size_t n, uint64_t seed)
{
    const uint8_t *b = p;
    uint64_t h = seed ^ (0x9E3779B97F4A7C15ull * ((uint64_t)n + 1));
    while (n >= 8) {
        uint64_t w;
        memcpy(&w, b, 8);
        h = (h ^ w) * 0xff51afd7ed558ccdull;
        h ^= h >> 29;
        b += 8;
        n -= 8;
    }
    uint64_t w = 0;
    memcpy(&w, b, n);
    h = (h ^ w ^ ((uint64_t)n << 56)) * 0xc4ceb9fe1a85ec53ull;
    return h ^ (h >> 32);
}

uint64_t hao_aot_guest_id(const void *mach_header, uint64_t avail, uint64_t slice_size)
{
    const struct mach_header_64 *h = mach_header;
    uint64_t len = avail < sizeof *h ? avail : sizeof *h;
    if (avail >= sizeof *h && h->sizeofcmds <= avail - sizeof *h) len = sizeof *h + h->sizeofcmds;
    return hao_aot_hash64(mach_header, (size_t)len, slice_size);
}

/* ------------------------------------------------------- code identity */

static void sha_update(CC_SHA256_CTX *c, const void *p, uint64_t n)
{
    while (n) {                                       /* CC_LONG is 32 bits */
        CC_LONG k = n > 0x40000000u ? 0x40000000u : (CC_LONG)n;
        CC_SHA256_Update(c, p, k);
        p = (const uint8_t *)p + k;
        n -= k;
    }
}
static void sha_u64(CC_SHA256_CTX *c, uint64_t v) { CC_SHA256_Update(c, &v, 8); }   /* x86_64: little-endian */

/* Every variable-length part is preceded by its length and every range by
 * its place in the image, so no two inputs give the same byte stream. */
void hao_aot_code_id(const void *mach_header, uint64_t cmds_len, const uint64_t *lo, const uint64_t *hi,
                     const uint8_t *const *code, int nranges, uint8_t out[HAO_AOT_ID_LEN])
{
    static const char tag[16] = "hao-aot-code-v1";
    CC_SHA256_CTX c;
    CC_SHA256_Init(&c);
    CC_SHA256_Update(&c, tag, sizeof tag);
    sha_u64(&c, cmds_len);
    sha_update(&c, mach_header, cmds_len);
    sha_u64(&c, (uint64_t)nranges);
    for (int k = 0; k < nranges; k++) {
        sha_u64(&c, lo[k]);
        sha_u64(&c, hi[k]);
        sha_update(&c, code[k], hi[k] - lo[k]);
    }
    CC_SHA256_Final(out, &c);
}

/* ---------------------------------------------------------- validation */

#define REJ(...) do { if (why && n) snprintf(why, n, __VA_ARGS__); return -1; } while (0)

int hao_aot_check(const void *buf, uint64_t size, const hao_aot_expect *x, hao_aot_view *v, char *why, size_t n)
{
    const uint8_t *b = buf;
    hao_aot_hdr h;
    if ((uintptr_t)buf & 7) REJ("unaligned buffer");
    if (size < sizeof h) REJ("truncated (%llu bytes)", (unsigned long long)size);
    memcpy(&h, b, sizeof h);
    if (memcmp(h.magic, HAO_AOT_MAGIC, 8) != 0) REJ("not a hao AOT v%u cache", HAO_AOT_VERSION);
    if (h.version != HAO_AOT_VERSION) REJ("format version %u, expected %u", h.version, HAO_AOT_VERSION);
    if (h.hdr_size != sizeof h) REJ("header size %u, expected %zu", h.hdr_size, sizeof h);
    if (h.file_size != size) REJ("file is %llu bytes, header says %llu", (unsigned long long)size, (unsigned long long)h.file_size);
    if (size > HAO_AOT_MAX_FILE) REJ("file larger than %llu MB", HAO_AOT_MAX_FILE >> 20);
    if (memcmp(h.uuid, x->uuid, 16) != 0) REJ("guest UUID differs");
    if (memcmp(h.gen, x->gen, 16) != 0) REJ("generated by another hao build or CPU profile");
    if (h.vmsize != x->vmsize) REJ("guest vmsize %#llx, cache says %#llx", (unsigned long long)x->vmsize, (unsigned long long)h.vmsize);
    if (h.guest_id != x->guest_id) REJ("guest load commands differ");
    /* The code identity: what the cache was translated from must be what
     * this image holds. Its kind follows from the image, never from the file. */
    if (x->id_kind != HAO_AOT_ID_CDHASH && x->id_kind != HAO_AOT_ID_CODE) REJ("this image has no code identity");
    if (h.id_kind != HAO_AOT_ID_CDHASH && h.id_kind != HAO_AOT_ID_CODE) REJ("unknown code identity kind %u", h.id_kind);
    if (h.id_kind != x->id_kind)
        REJ(x->id_kind == HAO_AOT_ID_CDHASH ? "translated from an unsigned guest; this image is code signed"
                                            : "translated from a code-signed guest; this image is not signed");
    if (!x->code_id) {
        if (why && n) snprintf(why, n, "this image's code identity has not been computed");
        return HAO_AOT_NEED_ID;
    }
    if (h.id_hash != x->id_hash || memcmp(h.code_id, x->code_id, HAO_AOT_ID_LEN) != 0) {
        /* cdhash: all 20 bytes; code hash: the first 8 are enough to tell two apart */
        int nb = h.id_kind == HAO_AOT_ID_CDHASH ? HAO_AOT_CDHASH_LEN : 8;
        char a[2 * HAO_AOT_CDHASH_LEN + 1], c[2 * HAO_AOT_CDHASH_LEN + 1];
        for (int k = 0; k < nb; k++) { snprintf(a + 2 * k, 3, "%02x", x->code_id[k]); snprintf(c + 2 * k, 3, "%02x", h.code_id[k]); }
        if (h.id_kind == HAO_AOT_ID_CDHASH)
            REJ("guest code differs: this image's cdhash is %s (hash type %u), the cache was translated from %s (hash type %u)",
                a, x->id_hash, c, h.id_hash);
        REJ("guest code differs: this image's code hash is %s..., the cache was translated from %s...", a, c);
    }
    if (h.nblocks > x->vmsize / 4) REJ("%u blocks for %llu guest instructions", h.nblocks, (unsigned long long)(x->vmsize / 4));
    uint64_t ents_sz = (uint64_t)h.nblocks * sizeof(hao_aot_ent), links_sz = (uint64_t)h.nlinks * sizeof(hao_aot_link);
    uint64_t total;
    if (__builtin_add_overflow((uint64_t)sizeof h, ents_sz, &total) || __builtin_add_overflow(total, links_sz, &total) ||
        __builtin_add_overflow(total, h.code_size, &total) || total != size)
        REJ("sizes do not add up (%u blocks, %u links, %llu code bytes, %llu-byte file)", h.nblocks, h.nlinks,
            (unsigned long long)h.code_size, (unsigned long long)size);
    if (h.code_size < 16) REJ("code area of %llu bytes", (unsigned long long)h.code_size);
    if ((uint64_t)h.nlinks > h.code_size / 5) REJ("%u links in %llu code bytes", h.nlinks, (unsigned long long)h.code_size);
    const uint8_t *payload = b + sizeof h;
    if (hao_aot_hash64(payload, (size_t)(size - sizeof h), 0) != h.payload_hash) REJ("payload hash mismatch");
    const hao_aot_ent *ents = (const hao_aot_ent *)(const void *)payload;
    const hao_aot_link *links = (const hao_aot_link *)(const void *)(payload + ents_sz);
    const uint8_t *code = payload + ents_sz + links_sz;
    for (uint32_t k = 0; k < h.nblocks; k++) {
        uint64_t g = ents[k].guest_off, c = ents[k].code_off;
        if (g & 3) REJ("block %u: guest offset %#llx not 4-aligned", k, (unsigned long long)g);
        bool in = false;
        for (int r = 0; r < x->nranges && !in; r++) in = g >= x->range_lo[r] && g + 4 <= x->range_hi[r];
        if (g >= x->vmsize || !in) REJ("block %u: guest offset %#llx outside the image's code", k, (unsigned long long)g);
        if (c & 15) REJ("block %u: code offset %#llx not 16-aligned", k, (unsigned long long)c);
        if (c < 16 || c >= h.code_size) REJ("block %u: code offset %#llx outside the code area", k, (unsigned long long)c);
        if (k && c <= ents[k - 1].code_off) REJ("block %u: code offsets not increasing", k);
    }
    for (uint32_t k = 0; k < h.nlinks; k++) {
        uint64_t s = links[k].site;
        if (s < 16 || s + 4 > h.code_size) REJ("link %u: site %#llx outside the code area", k, (unsigned long long)s);
        if (links[k].target >= h.nblocks) REJ("link %u: target block %u of %u", k, links[k].target, h.nblocks);
        int32_t rel;
        memcpy(&rel, code + s, 4);
        if ((int64_t)s + 4 + rel != (int64_t)ents[links[k].target].code_off) REJ("link %u does not reach its block", k);
    }
    if (v) { v->hdr = (const hao_aot_hdr *)buf; v->ents = ents; v->links = links; v->code = code; }
    return 0;
}

/* ------------------------------------------------- environment trust */

int hao_env_tier_for(const hao_proc_facts *f)
{
    int t = HAO_ENV_OPEN;
    /* Every root process, whoever started it: its environment may have come
     * through sudo, a login session or a job's plist from someone who is not
     * root, and what it would choose (code, paths, checks) runs as root. */
    if (f->pid == 1 || f->euid == 0 || f->restricted || f->entitled) t = HAO_ENV_GUARDED;
    /* A program Security.framework may answer for as Apple's (docs/security-model.md, Identity):
     * nothing from the environment may change what it loads or trusts. */
    if (f->identity) t = HAO_ENV_GUARDED;
    if (f->setugid || f->uid != f->euid || f->gid != f->egid) t = HAO_ENV_SETUGID;
    if (f->distrust > t) t = f->distrust > HAO_ENV_SETUGID ? HAO_ENV_SETUGID : f->distrust;
    return t;
}

/* Run the same guest code through a path every process already takes without
 * the switch: no cache file (HAO_NO_AOT), the interpreter a full code cache
 * or a process without executable memory falls back to (HAO_INTERP,
 * HAO_JIT_HELPERS_ONLY), an exit not chained yet (HAO_NO_CHAIN). They change
 * speed, not what is bound or how a native call is made. */
static const char *const engine_switches[] = {"HAO_NO_AOT", "HAO_INTERP", "HAO_NO_CHAIN", "HAO_JIT_HELPERS_ONLY", NULL};
/* Print to the process's own stderr or the console. They bind nothing and
 * turn nothing off (HAO_NX_STATS adds a thread that only prints). */
static const char *const diag_switches[] = {"HAO_VERBOSE", "HAO_CRASH_TRACE", "HAO_NX_STATS", "HAO_BRIDGE_STATS", NULL};
/* For hao's own tests: they replace a kernel answer or a resource limit with
 * a chosen one, or make a diagnostic fatal. Read only by a build with
 * HAO_TEST_SWITCHES defined, and there only in an OPEN process. */
static const char *const test_switches[] = {"HAO_LIBVAL_USER", "HAO_SIGRETURN_USER", "HAO_AOT_LIMIT_KB", "HAO_BRIDGE_ABORT",
                                            "HAO_NO_JIT_MEMORY", "HAO_CODE_ALIAS", NULL};

static bool listed(const char *const *l, const char *name)
{
    for (; *l; l++) if (!strcmp(*l, name)) return true;
    return false;
}

#ifdef HAO_TEST_SWITCHES
const bool hao_test_switches = true;
#else
const bool hao_test_switches = false;
#endif

bool hao_env_test_switch(const char *name) { return listed(test_switches, name); }

/* Everything not listed above is OPEN only, because it does one of:
 *  - choose code or paths: HAO_CACHE, HAO_TRUST_LIST, HAO_AOT_LEARN, HAO_GUEST_ROOT, HAO_IF_DIR,
 *    HAO_ASYNC_CONTRACT_LIBRARY, HAO_FLAGS, HAO_DIAG_DIR (a directory a root process would create a file in);
 *  - turn a check off: HAO_NO_LIBVAL;
 *  - change how native calls are made, so a correct program stops being one: HAO_NO_VARSNIFF (variadic natives
 *    read their arguments from the wrong registers, varsniff.c), HAO_NO_IFUNITS and HAO_NO_THUNKS (calls fall to
 *    the untyped bridge or are refused, bridge.c), HAO_NATIVE_LIBCXX (guest code meets a libc++ with another
 *    std::string layout, runtime.c), HAO_NO_MSGSEND, HAO_NO_CLOSURES, HAO_NO_SWIFTREG, HAO_NO_*_THUNKS,
 *    HAO_NO_SWIFT_VALUES, HAO_SWIFT_POP, HAO_BRIDGE_CHECK (binds Swift results the default leaves alone,
 *    swiftresult.c);
 *  - change signal or memory behaviour: HAO_SIGRETURN_KERNEL (a resumed fault dies where the kernel refuses the
 *    frame, signals.c), HAO_NO_PROBE, HAO_WATCHDOG (takes SIGALRM and exits 124), HAO_JIT_CACHE_MB.
 * A switch nobody listed is OPEN only too. SETUGID honours none: even an engine switch lets the caller slow a
 * set-ID program by orders of magnitude, which widens every race in it. */
bool hao_env_switch_allowed(const char *name, int tier)
{
    if (!hao_test_switches && listed(test_switches, name)) return false;
    if (tier <= HAO_ENV_OPEN) return true;
    return tier == HAO_ENV_GUARDED && (listed(engine_switches, name) || listed(diag_switches, name));
}

/* dyld's rule for a main executable that is set-user-ID or set-group-ID
 * (AMFI clears AMFI_DYLD_OUTPUT_ALLOW_AT_PATH and ..._ALLOW_PATH_VARS, so
 * ProcessConfig::Security has allowAtPaths and allowEnvVarsPath false;
 * dyld/Loader.cpp):
 *  - @executable_path is never expanded (Loader::expandAtExecutablePath:
 *    "@executable_path not expanded due to security policy");
 *  - @loader_path is not expanded in an LC_RPATH of the main executable; it
 *    still is in a load command and in another image's LC_RPATH
 *    (Loader::expandAtLoaderPath);
 *  - an LC_RPATH that is a relative path is skipped
 *    (Loader::forEachResolvedAtPathVar, rdar://81909581);
 *  - an install name that is a relative path is refused (Loader::getLoader:
 *    "relative path not allowed in hardened program", rdar://47682983).
 * The caller of a set-ID program chooses its working directory and, through
 * a hard link, the directory its path names, so these would let that caller
 * choose the code. Absolute paths and @rpath/ itself (expanded through the
 * LC_RPATHs this rule then filters) pass. */
bool hao_dep_path_allowed(const char *path, bool from_rpath, bool main_image, int tier, const char **why)
{
    const char *w = NULL;
    if (tier == HAO_ENV_SETUGID) {
        if (!strncmp(path, "@executable_path", 16) && (path[16] == '/' || !path[16]))
            w = "security policy does not allow @ path expansion";
        else if (!strncmp(path, "@loader_path", 12) && (path[12] == '/' || !path[12])) {
            if (from_rpath && main_image) w = "security policy does not allow @ path expansion";
        } else if (path[0] != '/' && path[0] != '@')
            w = "relative path not allowed in hardened program";
    }
    if (why) *why = w;
    return !w;
}

bool hao_entitlements_foreign(const char *xml, size_t n)
{
    static const char *const own[] = {"com.apple.security.cs.allow-jit", "com.apple.security.cs.disable-library-validation",
                                      "com.apple.security.get-task-allow", NULL};
    const char *p = xml, *e = xml + n;
    for (;;) {
        const char *k = memmem(p, (size_t)(e - p), "<key>", 5);
        if (!k) return false;
        k += 5;
        const char *ke = memmem(k, (size_t)(e - k), "</key>", 6);
        if (!ke) return true;                     /* malformed: assume the worst */
        bool ok = false;
        for (const char *const *o = own; *o && !ok; o++) ok = strlen(*o) == (size_t)(ke - k) && !memcmp(*o, k, (size_t)(ke - k));
        if (!ok) return true;
        p = ke + 6;
    }
}

/* ---------------------------------------------------- cache locations */

static bool at_or_under(const char *p, const char *dir)
{
    size_t l = strlen(dir);
    return !strncmp(p, dir, l) && (p[l] == 0 || p[l] == '/');
}

bool hao_aot_dir_is_system(int kind, const char *canon)
{
    if (kind == HAO_AOT_SYS || kind == HAO_AOT_SYS_RO) return true;
    return canon && (at_or_under(canon, HAO_AOT_SYS_DIR) || at_or_under(canon, HAO_AOT_SYS_RO_DIR));
}

static bool pw_dir_ok(const char *d)
{
    if (!d || d[0] != '/' || !strcmp(d, "/")) return false;
    if (!strncmp(d, "/var/empty", 10) && (d[10] == 0 || d[10] == '/')) return false;
    if (!strncmp(d, "/private/var/empty", 18) && (d[18] == 0 || d[18] == '/')) return false;
    return strlen(d) + sizeof "/Library/Caches/hao" < sizeof ((hao_aot_dir *)0)->path;
}

int hao_aot_dirs_for(int tier, uid_t euid, const char *pw_dir, const char *hao_cache, hao_aot_dir *out,
                     int *write_idx, char *why, size_t n)
{
    int k = 0;
    *write_idx = -1;
    if (why && n) why[0] = 0;
    if (tier == HAO_ENV_OPEN && hao_cache && hao_cache[0]) {
        if (hao_cache[0] != '/') { if (why && n) snprintf(why, n, "HAO_CACHE=%s is not absolute; AOT is off", hao_cache); return 0; }
        if (strlen(hao_cache) >= sizeof out[0].path) { if (why && n) snprintf(why, n, "HAO_CACHE is too long; AOT is off"); return 0; }
        snprintf(out[0].path, sizeof out[0].path, "%s", hao_cache);
        out[0].kind = HAO_AOT_EXPLICIT;
        *write_idx = 0;
        return 1;
    }
    snprintf(out[k].path, sizeof out[k].path, "%s", HAO_AOT_SYS_RO_DIR);
    out[k++].kind = HAO_AOT_SYS_RO;
    snprintf(out[k].path, sizeof out[k].path, "%s", HAO_AOT_SYS_DIR);
    out[k].kind = HAO_AOT_SYS;
    if (euid == 0 && tier != HAO_ENV_SETUGID) *write_idx = k;
    k++;
    if (tier == HAO_ENV_OPEN && euid >= 501 && euid < 0x80000000u && pw_dir_ok(pw_dir)) {
        size_t l = strlen(pw_dir);
        while (l > 1 && pw_dir[l - 1] == '/') l--;
        snprintf(out[k].path, sizeof out[k].path, "%.*s/Library/Caches/hao", (int)l, pw_dir);
        out[k].kind = HAO_AOT_USER;
        *write_idx = k;
        k++;
    }
    return k;
}

#define FAIL(...) do { if (why && n) snprintf(why, n, __VA_ARGS__); return false; } while (0)

bool hao_aot_dir_explicit(int tier, const char *dir, hao_aot_dir *out, char *why, size_t n)
{
    if (why && n) why[0] = 0;
    if (tier == HAO_ENV_SETUGID) FAIL("--cache is refused in a setuid/setgid process");
    if (!dir || dir[0] != '/') FAIL("--cache %s is not an absolute path", dir ? dir : "");
    if (strlen(dir) >= sizeof out->path) FAIL("--cache names a path that is too long");
    snprintf(out->path, sizeof out->path, "%s", dir);
    out->kind = HAO_AOT_EXPLICIT;
    return true;
}

bool hao_aot_stat_ok(const struct stat *st, int kind, int role, uid_t euid, char *why, size_t n)
{
    bool sys = kind == HAO_AOT_SYS || kind == HAO_AOT_SYS_RO;
    if (S_ISLNK(st->st_mode)) FAIL("is a symlink");
    if (role == HAO_AOT_FILE ? !S_ISREG(st->st_mode) : !S_ISDIR(st->st_mode))
        FAIL("not a %s", role == HAO_AOT_FILE ? "regular file" : "directory");
    if (!(st->st_uid == 0 || (!sys && st->st_uid == euid))) FAIL("owned by uid %u", (unsigned)st->st_uid);
    if ((st->st_mode & (S_IWGRP | S_IWOTH)) && !(role == HAO_AOT_ANCESTOR && !sys && (st->st_mode & S_ISVTX)))
        FAIL("writable by group or others (mode %o)", (unsigned)(st->st_mode & 07777));
    return true;
}

/* Does any allow entry grant a right that could change what the path holds
 * (write/add, append/add-subdirectory, delete, delete-child, attributes,
 * security, owner)? Read and search grants are harmless. An entry we cannot
 * read counts as granting. */
bool hao_aot_acl_allows(void *acl)
{
    static const acl_perm_t w[] = {ACL_WRITE_DATA, ACL_APPEND_DATA, ACL_DELETE, ACL_DELETE_CHILD, ACL_WRITE_ATTRIBUTES,
                                   ACL_WRITE_EXTATTRIBUTES, ACL_WRITE_SECURITY, ACL_CHANGE_OWNER};
    if (!acl) return false;
    acl_entry_t e;
    for (int id = ACL_FIRST_ENTRY; acl_get_entry((acl_t)acl, id, &e) == 0; id = ACL_NEXT_ENTRY) {
        acl_tag_t tag;
        acl_permset_t ps;
        if (acl_get_tag_type(e, &tag) != 0) return true;
        if (tag == ACL_EXTENDED_DENY) continue;
        if (acl_get_permset(e, &ps) != 0) return true;
        for (size_t k = 0; k < sizeof w / sizeof w[0]; k++)
            if (acl_get_perm_np(ps, w[k]) != 0) return true;
    }
    return false;
}

/* canon must be canonical (realpath): absolute, no "//", no trailing '/'. */
bool hao_aot_dir_ok(const char *canon, int kind, uid_t euid, char *why, size_t n)
{
    char p[1024], w[256];
    size_t len = strlen(canon);
    if (canon[0] != '/' || len >= sizeof p || strstr(canon, "//") || (len > 1 && canon[len - 1] == '/'))
        FAIL("%s: not a canonical absolute path", canon);
    /* "/", then each prefix ending before a '/' or at the end of canon */
    for (size_t i = 0;;) {
        size_t l = i ? i : 1;
        bool last = l >= len;
        memcpy(p, canon, l);
        p[l] = 0;
        struct stat st;
        if (lstat(p, &st) != 0) FAIL("%s: cannot stat", p);
        if (!hao_aot_stat_ok(&st, kind, last ? HAO_AOT_DIR : HAO_AOT_ANCESTOR, euid, w, sizeof w)) FAIL("%s: %s", p, w);
        acl_t a = acl_get_link_np(p, ACL_TYPE_EXTENDED);
        bool bad = hao_aot_acl_allows(a);
        if (a) acl_free(a);
        if (bad) FAIL("%s: its ACL grants write access", p);
        if (last) return true;
        i = l + 1;
        while (i < len && canon[i] != '/') i++;
    }
}

/* The configured (literal) path may pass through symlinks only if root owns
 * them (/tmp, /var, /etc); the canonical path is then checked in full. */
bool hao_aot_literal_ok(const char *path, char *why, size_t n)
{
    char p[1024];
    size_t len = strlen(path);
    if (path[0] != '/' || len >= sizeof p) FAIL("%s: not an absolute path", path);
    for (size_t i = 1; i <= len; i++) {
        if (i < len && path[i] != '/') continue;
        if (path[i - 1] == '/') continue;
        memcpy(p, path, i);
        p[i] = 0;
        struct stat st;
        if (lstat(p, &st) != 0) return true;      /* the rest does not exist yet */
        if (S_ISLNK(st.st_mode) && st.st_uid != 0) FAIL("%s is a symlink owned by uid %u", p, (unsigned)st.st_uid);
    }
    return true;
}
